import { writeFileSync } from 'node:fs';
import { sculptToGLSL } from 'shader-park-core';
import { recipes } from './flat-recipes.mjs';
import { membranes } from './membrane-recipes.mjs';

const header = `let p=getSpace(); let x=p.x; let y=p.y;
let n=input(6,3,12); let w=input(.3,0,1); let h=input(.1,0,1); let t=input(.12,.01,.3);`;
const gpu = [],
  cpu = [];
for (const [name, source] of Object.entries(recipes)) {
  const result = sculptToGLSL(header + source);
  const start = result.geoGLSL.indexOf('float surfaceDistance');
  const glsl = result.geoGLSL
    .slice(start)
    .replace('surfaceDistance', `flat_${name}`);
  if (start < 0 || /undefined|NaN/.test(glsl))
    throw new Error(`Invalid Shader Park output: ${name}`);
  gpu.push(glsl);
  cpu.push(
    `${name}: (x: number, y: number, n: number, w: number, h: number, t: number): number => {${source.replace('setSDF(', 'return (')}}`,
  );
}
const output =
  `// Generated by scripts/compile-flat-shaders.mjs using shader-park-core. Edit scripts/flat-recipes.mjs.\n` +
  `export const FLAT_SDF_GLSL = ${JSON.stringify(gpu.join('\n'))};\n` +
  `const {sqrt, sin, cos, pow, abs, min, max, atan2: atan} = Math;\n` +
  `const clamp = (x: number, a: number, b: number) => Math.max(a, Math.min(b,x));\n` +
  `const step = (edge: number, x: number) => x < edge ? 0 : 1;\n` +
  `export const flatDistances = {${cpu.join(',\n')}};\n`;
writeFileSync(
  new URL('../app/lib/render/flat-sdf.generated.ts', import.meta.url),
  output,
);
console.log(`Compiled ${gpu.length} flat figure recipes with Shader Park`);

const surface = sculptToGLSL(`
let p=getSpace(); let q=p.x; let along=p.y;
let section=input(.5,0,1); let folds=input(4,1,10); let twist=input(.5,0,2);
let inside=max(1-q*q,.0001);
let roundedProfile=sqrt(inside); let membrane=pow(inside,.26);
let ridge=sin(along*6.28318530718*folds+q*2+time*.22);
let height=mix(roundedProfile,membrane,section)+twist*q*ridge*.42+inside*ridge*.07;
setSDF(height);`);
const surfaceGLSL = surface.geoGLSL
  .slice(surface.geoGLSL.indexOf('float surfaceDistance'))
  .replace('surfaceDistance', 'sweepProfile');
if (/undefined|NaN/.test(surfaceGLSL))
  throw new Error('Invalid surface profile');
writeFileSync(
  new URL('../app/lib/render/surface.generated.ts', import.meta.url),
  `// Generated with Shader Park. Edit scripts/compile-flat-shaders.mjs.\nexport const SURFACE_GLSL = ${JSON.stringify(surfaceGLSL)};\n`,
);

const membraneGpu = [],
  membraneCpu = [];
for (const [name, source] of Object.entries(membranes)) {
  const result = sculptToGLSL(header + source);
  const glsl = result.geoGLSL
    .slice(result.geoGLSL.indexOf('float surfaceDistance'))
    .replace('surfaceDistance', `membrane_${name}`);
  if (/undefined|NaN/.test(glsl)) throw new Error(`Invalid membrane: ${name}`);
  membraneGpu.push(glsl);
  membraneCpu.push(
    `${name}: (x:number,y:number,n:number,w:number,h:number):number=>{${source.replace('setSDF(', 'return (')}}`,
  );
}
writeFileSync(
  new URL('../app/lib/render/membranes.generated.ts', import.meta.url),
  `// Generated with Shader Park. Edit scripts/membrane-recipes.mjs.\nexport const MEMBRANE_GLSL = ${JSON.stringify(membraneGpu.join('\n'))};\nconst {sqrt,sin,cos,pow,abs,min,max,atan2:atan}=Math;\nexport const membraneDistances={${membraneCpu.join(',\n')}};\n`,
);
